import fs from 'node:fs/promises';

const files = [
  '20260917232020_portfolio.sql',
  '20260918002851_explicit_table_grants.sql',
  '20261026174435_portfolio_translations.sql',
];
const sections = await Promise.all(files.map(async file => {
  const sql = await fs.readFile('supabase/migrations/' + file, 'utf8');
  // The three existing migrations run in one transaction for initial setup.
  return '-- SOURCE: ' + file + '\n' + sql.replace(/^(begin|commit);\s*$/gim, '');
}));
const guard = `-- GENERATED by scripts/build-supabase-setup.mjs from the existing migrations.
-- Run only in the NEW, EMPTY qr-cv Supabase project.
-- All changes roll back if any statement fails. Existing public tables are protected.
begin;
do $$ begin
  if exists (select 1 from information_schema.tables where table_schema = 'public' and table_type = 'BASE TABLE') then
    raise exception 'Public tables already exist. Stop and inspect migrations; do not reset the database.';
  end if;
end $$;
`;
await fs.writeFile('supabase/setup-new-project.sql', guard + sections.join('\n\n') + "\nnotify pgrst, 'reload schema';\ncommit;\n");
console.log('Created atomic setup for an empty project from ' + files.length + ' migrations.');
